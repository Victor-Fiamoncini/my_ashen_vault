from dataclasses import dataclass
from typing import ClassVar


@dataclass(frozen=True)
class Item:
    id: str
    name: str
    kind: str
    price: int = 0
    desc: str = ""
    power: int | None = None
    reach: float | None = None
    speed: float | None = None
    heal: int | None = None
    mana: int | None = None
    spell: str | None = None
    category: str | None = None  # weapons: see player/weapons.py
    level: int = 1  # lowest character level that can wield or wear it
    two_handed: bool = False  # weapons: fills both hands
    slot: str | None = None  # armor: "body" or "hands"
    guard: float | None = None  # shields: share of a frontal blow they stop (0..1)
    stability: float | None = None  # shields: damage a full ST bar can absorb


