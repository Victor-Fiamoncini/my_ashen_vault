GLYPHS = {ch: tuple(src.split()) for ch, src in _SRC.items()}
FALLBACK = GLYPHS["?"]


def glyph(ch):
    return GLYPHS.get(ch, FALLBACK)


def width(s):
    """Pixel width of `s`, without the trailing gap."""
    if not s:
        return 0
    return sum(len(glyph(ch)[0]) for ch in s) + GAP * (len(s) - 1)


def rects(s, x, y):
    """Yields (x, y, w, h) runs covering the lit pixels of `s`, top-left at (x, y).
    Unknown characters draw as '?'."""
    gx = x
    for ch in s:
        rows = glyph(ch)
        for row, bits in enumerate(rows):
            col = 0
            while col < len(bits):
                if bits[col] != "#":
                    col += 1
                    continue
                start = col
                while col < len(bits) and bits[col] == "#":
                    col += 1
                yield gx + start, y + row, col - start, 1
        gx += len(rows[0]) + GAP
